"""Saves static EDA charts to ./charts (useful for the project report). Run: python run_eda.py"""
from pathlib import Path
import pandas as pd, matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt, seaborn as sns
import canteen_analysis as ca

sns.set_theme(style="whitegrid", palette="viridis")
out = Path("charts")
out.mkdir(exist_ok=True)
df, log = ca.clean_data(pd.read_csv("canteen_sales.csv"))

def save(fig, name): fig.tight_layout(); fig.savefig(out / name, dpi=130); plt.close(fig)

d = ca.daily_sales(df)
fig, ax = plt.subplots(figsize=(10, 4))
ax.plot(d["Date"], d["Revenue"], alpha=.35)
ax.plot(d["Date"], d["Revenue"].rolling(7, min_periods=1).mean(), color="crimson", lw=2)
ax.set_title("Daily Sales Trend (red = 7-day average)")
save(fig, "1_daily_trend.png")
fig, ax = plt.subplots(figsize=(8, 4))
sns.barplot(data=ca.monthly_sales(df), x="Month", y="Revenue", ax=ax)
ax.set_title("Monthly Revenue")
save(fig, "2_monthly_revenue.png")
r = ca.item_ranking(df)
fig, ax = plt.subplots(figsize=(7, 4))
sns.barplot(data=r, y="Food Item", x="Revenue", ax=ax)
ax.set_title("Revenue by Food Item")
save(fig, "3_item_revenue.png")
fig, ax = plt.subplots(figsize=(7, 4))
sns.barplot(data=r.sort_values("Quantity", ascending=False), y="Food Item", x="Quantity", ax=ax, color="teal")
ax.set_title("Quantity by Food Item")
save(fig, "4_item_quantity.png")
fig, ax = plt.subplots(figsize=(6, 4))
sns.barplot(data=ca.category_sales(df), x="Category", y="Revenue", ax=ax)
ax.set_title("Category-wise Revenue")
save(fig, "5_category_revenue.png")
fig, ax = plt.subplots(figsize=(8, 4))
sns.heatmap(ca.weekday_month_pivot(df), annot=True, fmt=".0f", cmap="YlOrRd", ax=ax)
ax.set_title("Weekday x Month Revenue")
save(fig, "6_peak_heatmap.png")
f = ca.forecast(df)
fig, ax = plt.subplots(figsize=(10, 4))
ax.plot(f["test"]["Date"], f["test"]["Actual"], label="Actual")
ax.plot(f["test"]["Date"], f["test"]["Predicted"], label="Predicted")
ax.legend()
ax.set_title(f"Forecast test set ({f['best']})")
save(fig, "7_forecast.png")
open("summary_report.txt", "w", encoding="utf-8").write(ca.build_report(df, log))
print("Saved charts to ./charts and summary_report.txt")
